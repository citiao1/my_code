/*
 * 51 单片机流水灯程序
 *
 * 硬件约定：
 *   8 个 LED 分别由 P1.0 ~ P1.7 控制，采用低电平点亮的接法。
 *   对应位输出 0 时 LED 亮，输出 1 时 LED 灭。
 *   这里的说明以该接法为前提，实际亮灭还取决于电路连接。
 *
 * 当前效果：
 *   每次只点亮一个 LED，按 P1.0 -> P1.7 的顺序循环。
 *   每个状态调用 delay_ms(500) 保持一段时间，实际时长需要校准。
 *   反向流水代码保留在文件末尾的注释中，当前不参与编译。
 */

/* 包含标准 8051 特殊功能寄存器定义，使程序可以使用 P1 等寄存器。 */
#include <reg51.h>

/* Keil C51 中 unsigned char 为 8 位，范围为 0 ~ 255，适合保存端口数据。 */
typedef unsigned char u8;
/* Keil C51 中 unsigned int 为 16 位，范围为 0 ~ 65535，用于延时计数。 */
typedef unsigned int u16;

/* 0xff = 二进制 1111 1111：P1 的 8 位全部输出高电平，关闭所有 LED。 */
#define LED_OFF 0xff

/*
 * 软件忙等待延时。
 *
 * 参数 milliseconds：期望的毫秒数；传入 0 时不执行内层延时。
 * 返回值：无。
 * static：该函数仅在当前源文件内可见。
 *
 * 实现方法：
 *   外层控制延时单元的数量，内层执行 120 次空循环来消耗 CPU 时间。
 *   120 是经验计数值，不代表在所有硬件上都能准确延时 1 ms。
 *
 * 注意：
 *   实际时长受晶振频率、单片机机器周期及编译器优化影响。
 *   工程配置中的时钟为 24 MHz，不能仅根据函数名认定延时准确。
 *   延时期间 CPU 一直执行循环，主程序不能同时处理其他任务；
 *   若已启用中断，中断仍可响应，但会进一步影响实际延时时长。
 */
static void delay_ms(u16 milliseconds)
{
    /* 内层循环计数器，每一个延时单元都会从 0 重新开始计数。 */
    u16 i;

    /*
     * 后置 -- 先用当前值判断是否非 0，再将计数值减 1。
     * 例如传入 500，循环体执行 500 次；传入 0，循环体不执行。
     * 最后一次判断会使无符号计数值回绕，但此时循环已结束，
     * 且后续不再使用该局部参数，因此不影响这里的循环次数。
     */
    while (milliseconds-- != 0)
    {
        for (i = 0; i < 120; i++)
        {
            /* 空语句：不处理业务，仅用于软件延时；效果受优化影响。 */
            ;
        }
    }
}

/*
 * 程序入口：完成端口初始化后，不断重复一轮流水灯。
 * 这是 Keil C51 的单片机入口写法，程序不需要返回操作系统。
 */
void main(void)
{
    /* 当前要写入 P1 的 8 位灯光状态，其中唯一的 0 表示点亮位置。 */
    u8 pattern;
    /* 一轮流水的步数计数器，依次取 0 ~ 7，共控制 8 个 LED。 */
    u8 i;

    /* 进入流水循环前先熄灭所有 LED，建立明确的初始输出状态。 */
    P1 = LED_OFF;

    /* 永久循环：一轮流水结束后，重新从 P1.0 开始。 */
    while (1)
    {
        /* 0xfe = 1111 1110：仅最低位为 0，首先点亮 P1.0 对应的 LED。 */
        pattern = 0xfe;
        for (i = 0; i < 8; i++)
        {
            /* 整字节写入 P1，同时设置 P1.0 ~ P1.7 的输出状态。 */
            P1 = pattern;
            /* 保持当前 LED 状态；500 为延时参数，不保证实际为 500 ms。 */
            delay_ms(500);

            /*
             * 将唯一的 0 向高位移动，为下一个 LED 准备输出状态：
             *   1. pattern << 1：整体左移一位，最低位自动补 0。
             *   2. | 0x01：把最低位置 1，避免新补的 0 点亮额外 LED。
             *   3. (u8)：只保留低 8 位，丢弃左移后超出端口宽度的位。
             *
             * 实际写入 P1 的顺序：
             *   fe -> fd -> fb -> f7 -> ef -> df -> bf -> 7f
             * 对应点亮位置：
             *   P1.0 -> P1.1 -> P1.2 -> P1.3 ->
             *   P1.4 -> P1.5 -> P1.6 -> P1.7
             *
             * 最后一次移位得到 ff，但本轮已结束，不会将该值写入 P1；
             * 下一轮将 pattern 重置为 fe，所以没有额外的全灭等待阶段。
             */
            pattern = (u8)((pattern << 1) | 0x01);
        }

        /*
         * 以下为停用的反向流水代码，外层块注释使其不参与编译。
         *
         * 若取消下面代码的注释：
         *   pattern = 0x7f 从 P1.7 开始点亮；
         *   右移使点亮位置依次移动到 P1.0；
         *   | 0x80 将最高位置 1，避免右移补入的 0 额外点亮 P1.7。
         *
         * 反向输出顺序为：
         *   7f -> bf -> df -> ef -> f7 -> fb -> fd -> fe
         *
         * 与前面的正向循环同时启用后，会形成往返流水。
         * 注意两个循环都会显示端点状态，因此 P1.7 和 P1.0
         * 在换向时各连续保持两次延时，端点停留时间会更长。
         */
        /*pattern = 0x7f;
        for (i = 0; i < 8; i++)
        {
            P1 = pattern;
            delay_ms(500);
            pattern = (u8)((pattern >> 1) | 0x80);
        }
        */
    }
}
