DATAS SEGMENT
    SCORE    DB 100 
    MSG_PASS DB 'PASS', 0Dh, 0Ah, '$'
    MSG_FAIL DB 'FAILURE', 0Dh, 0Ah, '$'
DATAS ENDS

CODES SEGMENT
    ASSUME CS:CODES,DS:DATAS
START:
    MOV AX, DATAS
    MOV DS, AX

    MOV AL, SCORE       
    CMP AL, 60          
    JAE IS_PASS         


    LEA DX, MSG_FAIL    
    JMP PRINT_RES       

IS_PASS:
    LEA DX, MSG_PASS   

PRINT_RES:
    MOV AH, 09H        
    INT 21H

    MOV AH, 4CH
    INT 21H
CODES ENDS
END START


