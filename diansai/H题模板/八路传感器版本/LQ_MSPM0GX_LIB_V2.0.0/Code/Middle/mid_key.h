#ifndef __MID_KEY_H__
#define __MID_KEY_H__

/*******************************************************************************
 * @file    mid_key.h
 * @brief   按键中间层（Middle Layer）
 *
 * @note    本模块是工程内接触 LQ_key.h 的唯一入口，封装了：
 *          - KEY0 / KEY1 / KEY2 三个按键的初始化与周期扫描
 *          - K1 短按 → 启动 / 急停 状态机切换
 *            启动前自动调用 MID_IMU_CalibrateGyro() 做陀螺仪零偏校准
 *
 *          隔离原则：
 *          - 业务层只通过本模块使用按键，严禁直接 include LQ_key.h
 *          - 启停状态由本模块私有维护（s_running）
 *          - 急停 → 启动时三环使能全开（默认速度由 param.c 决定）
 *          - 启动 → 急停时三环使能全关 + chassis_vx=0 + 强制电机停
 *          - 上电默认状态 = 急停（需短按 K1 启动）
 *
 * @author  LQ_012
 * @date    2026-07-27
 *******************************************************************************/

#include "include.h"

/* ============================================================
 *  K1/K2 发车模式可调参数（用户声明"暂定后续还要改"，集中在此便于调整）
 * ============================================================ */

/* K1 减速触发里程阈值（mm），达到此里程开始减速（默认 3000mm=3m，可调） */
#define MID_KEY_K1_DECEL_THRESHOLD_MM (2580.0f)

/* 减速/加速步进周期（ms），由调度器按此周期调用 MID_Chassis_RampStep（默认 20ms） */
#define MID_KEY_RAMP_PERIOD_MS        (50u)

/* ============================================================
 *  按键编号（与 LQEnum_KEYn_t 对齐，屏蔽驱动层细节）
 * ============================================================ */
typedef enum {
    MID_KEY_0 = 0,    /* 母板按键 0（PB14） */
    MID_KEY_1 = 1,    /* 母板按键 1（PB15）—— 启停 / 校准 */
    MID_KEY_2 = 2,    /* 母板按键 2（PB16） */
} MID_Key_t;

/* ============================================================
 *  发车模式枚举（供调度器/显示层判断当前运行模式）
 * ============================================================ */
typedef enum {
    MID_MODE_IDLE = 0,   /* 停止状态 */
    MID_MODE_K1    = 1,   /* K1 快发+按里程减速模式 */
    MID_MODE_K2    = 2,   /* K2 慢发+渐进加速模式 */
} MID_LaunchMode_t;

/* ============================================================
 *  启停状态查询
 * ============================================================ */

/* 查询当前是否处于运行状态
 * @return  1 = 运行中（三环使能全开）
 *          0 = 急停（三环使能全关 + 速度清零 + 电机停）
 */
uint8_t MID_Key_IsRunning(void);

/* 查询当前发车模式
 * @return MID_MODE_IDLE（停止）/ MID_MODE_K1 / MID_MODE_K2
 * @note  供 app_scheduler 判断是否跳过紧急停车、main.c 判断是否显示里程
 */
MID_LaunchMode_t MID_Key_GetLaunchMode(void);

/* 查询当前模式的巡航速度（ramp 收敛目标）
 * @return K1/K2 发车时保存的模式巡航速度；IDLE 时返回 0
 * @note  供 MID_Chassis_RampStep 作为减速终点/加速目标的基准
 */
float MID_Key_GetCruiseVx(void);

/* ============================================================
 *  初始化 / 周期扫描
 * ============================================================ */

/* 初始化按键 GPIO
 * @note  必须在 main() 中先于 MID_Key_Scan() 调用一次
 *        内部调用 LQ_Key_Init() 配置 PB14/15/16 + 拨码开关为上拉输入
 */
void MID_Key_Init(void);

/* 按键周期扫描，请在主循环 while(1) 中每帧调用
 * @note  内部每 20ms 实调一次 LQ_Key_Scan
 *        - K1 短按：自动切换 启动/急停
 *          · 急停 → 启动：先调 MID_IMU_CalibrateGyro() 校准，
 *                       再调 MID_Chassis_Start() 打开三环使能
 *          · 启动 → 急停：调 MID_Chassis_Stop() 关三环 + 清速度 + 停电机
 *        - K0 / K2 短按：预留接口，当前不绑定任何动作
 *  前置条件：
 *          1. main() 已先调用 MID_Key_Init()
 *          2. main() 已先调用 APP_Scheduler_Init() 提供 1ms 时基
 *          3. 启动分支需先完成 IMU 初始化（否则校准函数会失败）
 */
void MID_Key_Scan(void);

#endif
