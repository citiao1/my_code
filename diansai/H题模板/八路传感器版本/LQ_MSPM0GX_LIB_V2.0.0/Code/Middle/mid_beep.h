#ifndef __MID_BEEP_H__
#define __MID_BEEP_H__

/*******************************************************************************
 * @file    mid_beep.h
 * @brief   蜂鸣器驱动（Middle Layer）
 *
 * @note    封装 LQ_GPIO，控制有源蜂鸣器的开关。
 *          - 有源蜂鸣器：内部带振荡源，给电平就响，GPIO 高/低电平控制开关。
 *          - 无源蜂鸣器：需要 PWM 驱动，频率决定音调，本模块不适用，请改用 LQ_PWM。
 *
 *          有效触发电平由宏 MID_BEEP_ACTIVE_LEVEL 控制：
 *          - 1：高电平响（默认，常见于高电平触发模块）
 *          - 0：低电平响（常见于低电平触发模块，如三极管下拉驱动）
 *
 *          引脚由宏 MID_BEEP_PIN 控制，默认 PA28。
 *          选 PA28 的理由：
 *            1) 板载 S8050 三极管驱动，高电平有效（板载上拉到 VCC，
 *               PA28 输出高电平 → 三极管导通 → 蜂鸣器通电鸣响）；
 *            2) 与现有模块（电机 PB2/3、PB10/11、编码器 PA7/PA3/PA8/PB7、
 *               UART0 PA10/PA11、灰度 PA22~PA27、MPU6050 PA12/PA14）均无冲突。
 *
 *          ※ 本工程使用有源蜂鸣器（通电即响、掉电即停），
 *            不需要 PWM，PA28 保持普通 GPIO 即可。
 *
 *          使用流程：
 *            1) MID_Beep_Init()  初始化 GPIO（推挽输出，默认关闭）
 *            2) MID_Beep_On()    响
 *            3) MID_Beep_Off()   停
 *            4) MID_Beep_Toggle() 翻转状态（响/停）
 *******************************************************************************/

#include "include.h"

/* ============================================================
 *  硬件配置宏（按实际接线修改）
 * ============================================================ */

/* 蜂鸣器控制引脚（默认 PA28，板载 S8050 三极管高电平驱动） */
#define MID_BEEP_PIN                   (GPIO_Pin_A_28)

/* 有效触发电平：1=高电平响，0=低电平响（按蜂鸣器模块类型修改） */
#define MID_BEEP_ACTIVE_LEVEL          (1u)

/* ============================================================
 *  API
 * ============================================================ */

/* 初始化蜂鸣器 GPIO（推挽输出，默认关闭）
 * @note  内部调用 LQ_GPIO_Init，配置为推挽输出，初始状态为"关闭"
 *        必须在使用 On/Off/Toggle 之前调用一次
 *        重复调用无副作用，仅重新配置 GPIO
 */
void MID_Beep_Init(void);

/* 打开蜂鸣器（响）
 * @note  向 MID_BEEP_PIN 写入有效电平 MID_BEEP_ACTIVE_LEVEL
 */
void MID_Beep_On(void);

/* 关闭蜂鸣器（停）
 * @note  向 MID_BEEP_PIN 写入关闭电平（与有效电平相反）
 */
void MID_Beep_Off(void);

/* 翻转蜂鸣器状态（响<->停）
 * @note  内部调用 LQ_GPIO_TogglePin，适合主循环周期性翻转做"滴滴"报警
 */
void MID_Beep_Toggle(void);

/* ============================================================
 *  报警 API（阻塞式，每次响声时长 + 响声间隔都按入参精确控制）
 * ============================================================ */

/* 蜂鸣器报警：连续响 count 次，每次响 on_seconds 秒，相邻两声间隔 gap_seconds 秒
 * @param  count        响声次数，传 0 直接返回、不响
 * @param  on_seconds   每次响的时长（秒），支持小数（0.05f / 1.5f 均可），<=0 直接返回
 * @param  gap_seconds  相邻两声之间的静默时长（秒），支持小数；<0 直接返回
 *                      传 0 表示两声紧贴（无间隔）
 *
 * @note   - 阻塞式实现：内部用 delay_ms 延时，调用期间主循环不跑
 *         - 适合初始化确认、按键反馈、错误报警等"独立短事件"
 *           （总时长建议 < 1~2s，否则会明显卡住控制环）
 *         - 若必须在主循环中非阻塞地使用，请基于
 *           MID_Beep_On / MID_Beep_Off 自行实现状态机
 *         - 末次响声之后不再追加间隔
 *
 * @example  MID_Beep_Beep(3, 0.5f,  0.1f);  // 滴0.5s 静0.1s 滴0.5s 静0.1s 滴0.5s
 *           MID_Beep_Beep(1, 1.0f,  0.0f);  // 长鸣 1 秒（无间隔参数）
 *           MID_Beep_Beep(5, 0.05f, 0.05f); // 紧凑快响，5 声各 50ms
 */
void MID_Beep_Beep(uint8_t count, float on_seconds, float gap_seconds);

#endif
